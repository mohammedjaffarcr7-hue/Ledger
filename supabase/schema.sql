-- Daftar database schema for Supabase.
-- Run this once in Supabase → SQL Editor → New query → paste → Run.
-- It is safe to run again: it only creates what is missing and replaces functions/policies.

-- ---------------------------------------------------------------
-- Profiles: one row per login, created automatically on sign-up.
-- ---------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  email       text,
  full_name   text not null default '',
  role        text not null default 'user' check (role in ('user','admin')),
  disabled    boolean not null default false,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------
-- Each user's own data. ids are generated by the app.
-- ---------------------------------------------------------------
create table if not exists public.accounts (
  id            text primary key,
  user_id       uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  name          text not null,
  kind          text not null default 'Cash',
  currency      text not null default 'IQD',
  opening       numeric not null default 0,
  created_ms    bigint not null default (extract(epoch from now())*1000)::bigint,
  updated_at    timestamptz not null default now()
);

create table if not exists public.people (
  id            text primary key,
  user_id       uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  name          text not null,
  created_ms    bigint not null default (extract(epoch from now())*1000)::bigint,
  updated_at    timestamptz not null default now()
);

create table if not exists public.entries (
  id            text primary key,
  user_id       uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  type          text not null check (type in ('income','expense','transfer','exchange','debt')),
  amount        numeric not null check (amount > 0),
  account       text,              -- account id ('' or null = no cash moved, debts only)
  to_account    text,
  to_amount     numeric,
  category      text,
  note          text not null default '',
  date          date not null default current_date,
  person        text,
  dir           text check (dir is null or dir in ('lent','borrowed','collected','repaid')),
  currency      text,
  created_ms    bigint not null default (extract(epoch from now())*1000)::bigint,
  updated_at    timestamptz not null default now(),
  updated_by    uuid default auth.uid()
);

create index if not exists entries_user_date on public.entries(user_id, date desc);
create index if not exists entries_date on public.entries(date desc);
create index if not exists accounts_user on public.accounts(user_id);
create index if not exists people_user on public.people(user_id);

-- ---------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin' and not disabled);
$$;

create or replace function public.is_active() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id = auth.uid() and not disabled);
$$;

-- New sign-up → profile row. The very first user to sign up becomes admin.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, email, full_name, role)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name',''),
          case when exists(select 1 from public.profiles) then 'user' else 'admin' end)
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Only admins can change role / disabled / email on a profile.
create or replace function public.guard_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if (new.role is distinct from old.role or new.disabled is distinct from old.disabled or new.email is distinct from old.email)
     and auth.uid() is not null and not public.is_admin() then
    raise exception 'Only an admin can change role, status or email';
  end if;
  if new.id = auth.uid() and old.role = 'admin' and (new.role <> 'admin' or new.disabled) then
    raise exception 'You cannot remove your own admin access';
  end if;
  return new;
end $$;

drop trigger if exists profiles_guard on public.profiles;
create trigger profiles_guard before update on public.profiles
  for each row execute function public.guard_profile();

create or replace function public.touch() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists entries_touch on public.entries;
create trigger entries_touch before update on public.entries for each row execute function public.touch();
drop trigger if exists accounts_touch on public.accounts;
create trigger accounts_touch before update on public.accounts for each row execute function public.touch();
drop trigger if exists people_touch on public.people;
create trigger people_touch before update on public.people for each row execute function public.touch();

-- ---------------------------------------------------------------
-- Row level security: each person sees only their own rows;
-- admins see and manage everything; disabled users see nothing.
-- ---------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.accounts enable row level security;
alter table public.people   enable row level security;
alter table public.entries  enable row level security;

drop policy if exists "profile read"   on public.profiles;
drop policy if exists "profile update" on public.profiles;
drop policy if exists "profile delete" on public.profiles;
create policy "profile read"   on public.profiles for select using (id = auth.uid() or public.is_admin());
create policy "profile update" on public.profiles for update using (id = auth.uid() or public.is_admin()) with check (id = auth.uid() or public.is_admin());
create policy "profile delete" on public.profiles for delete using (public.is_admin() and id <> auth.uid());

do $$
declare t text;
begin
  foreach t in array array['accounts','people','entries'] loop
    execute format('drop policy if exists "own rows" on public.%I', t);
    execute format('drop policy if exists "admin rows" on public.%I', t);
    execute format($p$create policy "own rows" on public.%I for all
                     using (user_id = auth.uid() and public.is_active())
                     with check (user_id = auth.uid() and public.is_active())$p$, t);
    execute format($p$create policy "admin rows" on public.%I for all
                     using (public.is_admin()) with check (public.is_admin())$p$, t);
  end loop;
end $$;

-- ---------------------------------------------------------------
-- Back-office views (run with the caller's rights, so only admins see everyone).
-- ---------------------------------------------------------------
create or replace view public.admin_entries with (security_invoker = true) as
  select e.*,
         p.email, p.full_name,
         a.name  as account_name,  a.currency as account_currency,
         ta.name as to_account_name, ta.currency as to_account_currency,
         pe.name as person_name
  from public.entries e
  join public.profiles p on p.id = e.user_id
  left join public.accounts a  on a.id  = e.account
  left join public.accounts ta on ta.id = e.to_account
  left join public.people  pe on pe.id = e.person;

create or replace view public.admin_users with (security_invoker = true) as
  select p.*,
         (select count(*) from public.accounts a where a.user_id = p.id) as accounts_count,
         (select count(*) from public.entries  e where e.user_id = p.id) as entries_count,
         (select max(e.updated_at) from public.entries e where e.user_id = p.id) as last_activity
  from public.profiles p;

grant select on public.admin_entries, public.admin_users to authenticated;
